import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const solverAssetNames = ["coordinates-web-v1.bin.gz", ...[4, 5, 6, 7].map(size => `nxn-${size}-v1.bin.gz`)];

export async function buildSolverAssets() {
  const entries = [];
  for (const name of solverAssetNames) {
    const coordinates = name.startsWith("coordinates");
    const bytes = await readFile(new URL(coordinates ? `./${name}` : `../internal/cube/tables/${name}`, import.meta.url));
    if (!coordinates) await writeFile(new URL(`./${name}`, import.meta.url), bytes);
    const key = coordinates ? "coordinates" : name.slice(0, 5);
    const digest = createHash("sha256").update(bytes).digest();
    entries.push(`${JSON.stringify(key)}: { url: new URL(${JSON.stringify(`./${name}`)}, import.meta.url), bytes: ${bytes.length}, digest: ${JSON.stringify(digest.toString("hex"))}, integrity: ${JSON.stringify(`sha256-${digest.toString("base64")}`)} }`);
  }
  await writeFile(new URL("./solver-assets.js", import.meta.url), `// Generated by make web; asset bytes and integrity belong to this release.\nexport const solverAssets = {\n${entries.join(",\n")}\n};\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildSolverAssets();
